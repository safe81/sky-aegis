SS=3

def S(v): return int(round(v*SS))
def pts(arr): return [(S(x),S(y)) for x,y in arr]

def gradient(size, top, bottom, horizontal=False):
    w,h=size; im=Image.new('RGBA',(w,h)); p=im.load()
    span=w if horizontal else h
    for i in range(span):
        t=i/max(1,span-1)
        c=tuple(int(top[k]*(1-t)+bottom[k]*t) for k in range(4))
        if horizontal:
            for y in range(h): p[i,y]=c
        else:
            for x in range(w): p[x,i]=c
    return im

def fill_poly_gradient(im, poly, top, bottom, outline=None, ow=1):
    m=Image.new('L',im.size,0); md=ImageDraw.Draw(m); md.polygon(pts(poly),fill=255)
    g=gradient(im.size,top,bottom)
    im.alpha_composite(Image.composite(g,Image.new('RGBA',im.size,(0,0,0,0)),m))
    if outline:
        ImageDraw.Draw(im).line(pts(poly+[poly[0]]),fill=outline,width=S(ow),joint='curve')

def glow(im, circles):
    g=Image.new('RGBA',im.size,(0,0,0,0)); d=ImageDraw.Draw(g)
    for x,y,r,c in circles:
        for k in range(7,0,-1):
            rr=S(r*k/3.0); a=int(c[3]*(k/7)**2*.16)
            d.ellipse((S(x)-rr,S(y)-rr,S(x)+rr,S(y)+rr),fill=(c[0],c[1],c[2],a))
    g=g.filter(ImageFilter.GaussianBlur(S(5)))
    im.alpha_composite(g)

def downsave(im,name,size):
    im=im.resize(size,Image.Resampling.LANCZOS)
    im.save(OUT/name,optimize=True)

def line(d,xy,fill,width=1): d.line(pts(xy),fill=fill,width=S(width),joint='curve')

def ellipse(d,box,fill=None,outline=None,width=1):
    b=tuple(S(x) for x in box); d.ellipse(b,fill=fill,outline=outline,width=S(width))

def rect(d,box,fill=None,outline=None,width=1,r=0):
    b=tuple(S(x) for x in box)
    if r: d.rounded_rectangle(b,radius=S(r),fill=fill,outline=outline,width=S(width))
    else: d.rectangle(b,fill=fill,outline=outline,width=S(width))

